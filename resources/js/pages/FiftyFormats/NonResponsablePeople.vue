<script setup>
  import { ref, computed, onMounted, watch } from 'vue';
  import { useI18n } from 'vue-i18n';
  import { useRouter } from 'vue-router';

  import AppBar from '@/components/AppBar.vue';
  import FilterableTable from '@/components/FilterableTable.vue';
  import PeekButton from '@/components/PeekButton.vue';
  import FlyToMapButton from '@/components/FlyToMapButton.vue';
  import DeleteConfirmDialog from '@/components/DeleteConfirmDialog.vue';
  import GlobalPagination from '@/components/GlobalPagination.vue';

  import { useMawadRepository } from '@/stores/MawadRepository';
  import { usePageRefresh } from '@/composables/usePageRefresh';

  usePageRefresh('/app/nonresponsablepeople', fetchAll);
  const repo = useMawadRepository();
  const router = useRouter();

  /* i18n / RTL */
  const { t, locale } = useI18n();
  const isRtl = ref(locale.value === 'fa');
  watch(locale, (l) => (isRtl.value = l === 'fa'));

  /* Snackbar */
  const showError = ref(false);
  const errorMessage = ref('');
  const showErrorMessage = (m) => {
    errorMessage.value = m;
    showError.value = true;
  };

  /* 🔗 go to Resources page for this resource_code */
  function goToResource(row) {
    if (!row?.resource_code) return;
    router.push(`/app/resources/${row.resource_code}`);
  }

  /* Helpers */
  const getRow = (s) => (s && s.raw ? s.raw : s);

  /* rows from store */
  const rowsFT = computed(() => {
    const list = repo.NonResponsablePeoples || [];
    if (Array.isArray(list)) return list;
    if (Array.isArray(list.data)) return list.data;
    return [];
  });

  /* 🔢 Filter cards state */
  const cardFilter = ref('all');

  const stats = computed(() => {
    const rows = rowsFT.value || [];
    const total = rows.length;
    const withCoordinates = rows.filter(
      (r) => r && r.coordinates && String(r.coordinates).trim() !== ''
    ).length;
    const withPhone = rows.filter(
      (r) => r && r.phone_number && String(r.phone_number).trim() !== ''
    ).length;
    const withJob = rows.filter((r) => r && r.now_job && String(r.now_job).trim() !== '').length;

    return { total, withCoordinates, withPhone, withJob };
  });

  const filteredRowsFT = computed(() => {
    const base = rowsFT.value || [];
    switch (cardFilter.value) {
      case 'withCoordinates':
        return base.filter((r) => r && r.coordinates && String(r.coordinates).trim() !== '');
      case 'withPhone':
        return base.filter((r) => r && r.phone_number && String(r.phone_number).trim() !== '');
      case 'withJob':
        return base.filter((r) => r && r.now_job && String(r.now_job).trim() !== '');
      default:
        return base;
    }
  });

  /* TABLE HEADERS – ALL INPUTS + map */
  const headersFT = computed(() => [
    { title: t('عکس'), key: 'picture', sortable: false },
    { title: t('نام مستعار'), key: 'nick_name' },
    { title: t('نام'), key: 'name' },
    { title: t('نام پدر'), key: 'father_name' },

    { title: t('ولایت اصلی'), key: 'main_province' },
    { title: t('ولسوالی اصلی'), key: 'main_district' },
    { title: t('قریه/ناحیه اصلی'), key: 'main_village' },

    { title: t('ولایت فعلی'), key: 'now_province' },
    { title: t('زون فعلی'), key: 'now_zone' },
    { title: t('ولسوالی فعلی'), key: 'now_district' },
    { title: t('قریه/ناحیه فعلی'), key: 'now_village' },

    { title: t('موقعیت مشخص'), key: 'now_specific_place' },
    { title: t('شماره سرک'), key: 'now_street_number' },
    { title: t('شماره خانه'), key: 'now_home_number' },
    { title: t('مختصات'), key: 'coordinates' },

    { title: t('تعداد دوستان'), key: 'friends_quantity' },
    { title: t('تمویل‌کننده'), key: 'supplier' },
    { title: t('شماره تماس'), key: 'phone_number' },
    { title: t('سابقه جرم'), key: 'history_jorm' },
    { title: t('محل فعالیت'), key: 'activity_place' },
    { title: t('وظیفه قبلی'), key: 'old_job' },
    { title: t('وظیفه فعلی'), key: 'now_job' },

    { title: t('نوع سلاح'), key: 'gun_type' },
    { title: t('تنظیم'), key: 'tanzim' },
    { title: t('نوع تخلف'), key: 'takhalof_type' },

    { title: t('کود منبع'), key: 'resource_code' },
    { title: t('شماره منبع'), key: 'resource_phone' },

    { title: t('نقشه'), key: 'map', sortable: false },
    { title: t('یادداشت'), key: 'note' },
  ]);

  /* TOP GROUPS – like old component */
  const topGroups = computed(() => [
    { title: t('مشخصات'), keys: ['name', 'nick_name', 'father_name'] },
    { title: t('آدرس اصلی'), keys: ['main_province', 'main_district', 'main_village'] },
    { title: t('آدرس فعلی'), keys: ['now_province', 'now_zone', 'now_district', 'now_village'] },
    {
      title: t('موقعیت/خانه'),
      keys: ['now_specific_place', 'now_street_number', 'now_home_number'],
    },
    {
      title: t('فعالیت/تماس'),
      keys: ['friends_quantity', 'supplier', 'phone_number', 'activity_place', 'coordinates'],
    },
    { title: t('سوابق/وظایف'), keys: ['history_jorm', 'old_job', 'now_job'] },
    { title: t('امنیتی'), keys: ['gun_type', 'tanzim', 'takhalof_type'] },
    {
      title: t('منبع/یادداشت'),
      keys: ['resource_code', 'resource_phone', 'note', 'Province_addr'],
    },
  ]);

  const filters = ref({});

  /* Peek */
  const expanded = ref(false);
  const selectedId = ref(null);
  const loadingOne = ref(false);
  const detail = ref(null);

  async function fetchOne(id) {
    loadingOne.value = true;
    try {
      if (typeof repo.FetchNonResponsablePeople === 'function') {
        await repo.FetchNonResponsablePeople(id);
        const single = Array.isArray(repo.NonResponsablePeople)
          ? repo.NonResponsablePeople[0]
          : repo.NonResponsablePeople;
        detail.value = single || {};
      } else {
        await fetchAll();
        const list = rowsFT.value || [];
        detail.value = list.find((r) => r.id === id) || {};
      }
    } catch (e) {
      console.error(e);
      showErrorMessage(t('خطا در دریافت معلومات اشخاص غیرمسؤول'));
    } finally {
      loadingOne.value = false;
    }
  }

  function openPeek(payload) {
    const row = getRow(payload);
    if (!row?.id) return;
    selectedId.value = row.id;
    expanded.value = true;
    fetchOne(row.id);
  }

  /* navigation */
  function goCreate() {
    router.push('/app/non-responsable-people-form');
  }

  function goEdit(payload) {
    const row = getRow(payload);
    if (!row?.id) return;
    router.push(`/app/non-responsable-people-form/${row.id}`);
  }

  const imgDialog = ref(false);
  const imgSrc = ref('');

  function openImg(row) {
    imgSrc.value = row?.picture || '';
    imgDialog.value = true;
  }

  /* delete with dialog */
  const deleteDialog = ref(false);
  const deleteTarget = ref(null);

  function openDeleteDialog(payload) {
    const row = getRow(payload);
    if (!row?.id) return;
    deleteTarget.value = row;
    deleteDialog.value = true;
  }

  async function handleDeleteConfirmed(target) {
    const row = target || deleteTarget.value;
    deleteDialog.value = false;
    if (!row?.id) return;
    try {
      await repo.DeleteNonResponsablePeople?.(row.id);
      await fetchAll();
      showErrorMessage(t('حذف شد'));
    } catch (e) {
      console.error(e);
      showErrorMessage(t('خطا در حذف'));
    } finally {
      deleteTarget.value = null;
    }
  }

  /* fetch all */
  async function fetchAll() {
    try {
      await repo.FetchNonResponsablePeoplesData?.();
    } catch (e) {
      console.error(e);
      showErrorMessage(t('خطا در دریافت فهرست اشخاص غیرمسؤول'));
    }
  }

  function handleSearch() {
    repo.page = 1;
    fetchAll();
  }

  function clearSearch() {
    repo.Search = '';
    repo.page = 1;
    fetchAll();
  }

  function handlePageChange(val) {
    repo.page = val;
    fetchAll();
  }

  function handlePerPageChange(val) {
    repo.itemsPerPage = val;
    repo.page = 1;
    fetchAll();
  }

  /* init */
  onMounted(async () => {
    await repo.GetResourceCode?.();
    await fetchAll();
  });
</script>

